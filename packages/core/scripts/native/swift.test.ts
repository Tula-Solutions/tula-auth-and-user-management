import { describe, expect, test } from 'bun:test'
import { DEFAULT_THEME, THEME_TOKENS } from '@tula-tech/contract/theme'
import { fixture, object, SAMPLE_SCHEMAS } from './fixture'
import { buildModel } from './model'
import {
  renderSwiftErrorCodes,
  renderSwiftOperations,
  renderSwiftSchemas,
  renderSwiftSupport,
  renderSwiftTheme,
  swiftType,
} from './swift'

const model = buildModel(fixture(SAMPLE_SCHEMAS), [])
const schemas = renderSwiftSchemas(model)

/** The lines of `text`, joined: an expectation written as the lines the file must hold. */
const lines = (...text: string[]) => text.join('\n')

describe('swiftType', () => {
  test.each([
    [{ kind: 'string' }, 'String'],
    [{ kind: 'integer' }, 'Int'],
    [{ kind: 'number' }, 'Double'],
    [{ kind: 'boolean' }, 'Bool'],
    [{ kind: 'json' }, 'TulaJSONValue'],
    [{ kind: 'named', name: 'FlowStep' }, 'FlowStep'],
    [{ kind: 'array', items: { kind: 'array', items: { kind: 'string' } } }, '[[String]]'],
    [{ kind: 'map', values: { kind: 'named', name: 'Cell' } }, '[String: Cell]'],
    [{ kind: 'array', items: { kind: 'nullable', of: { kind: 'integer' } } }, '[Int?]'],
  ] as const)('%j is %s', (type, expected) => {
    expect(swiftType(type)).toBe(expected)
  })
})

describe('the Swift schemas file', () => {
  test('starts by saying it is generated, by which command, and imports Foundation only', () => {
    expect(schemas.split('\n').slice(0, 6)).toEqual([
      '// Generated by `bun run native:generate` from packages/contract/openapi.json and @tula-tech/contract.',
      '// Do not edit: change the API or the contract, run `bun run contract:generate`, then regenerate this file.',
      '// A value of these types may hold tokens, passwords and attempt secrets: never log, print or interpolate one.',
      '',
      'import Foundation',
      '',
    ])
    expect(schemas.match(/^import .*$/gm)).toEqual(['import Foundation'])
    expect(schemas.endsWith('}\n')).toBe(true)
  })

  test('declarations are in order of name', () => {
    const names = [...schemas.matchAll(/^public (?:struct|enum|typealias) (\w+)/gm)].map(
      ([, name]) => name
    )
    expect(names).toEqual([...names].sort())
    expect(names).toEqual([
      'Answer',
      'AnswerNothing',
      'Colour',
      'How',
      'HowByCode',
      'HowByLink',
      'Params',
      'Request',
      'Size',
      'Step',
      'StepComplete',
      'StepNeedsPassword',
    ])
  })

  test('a property: camelCase, a keyword in backticks, optional where it may be absent or null', () => {
    expect(schemas).toContain(
      lines(
        '/// What the thing answered.',
        'public struct Answer: Codable, Hashable, Sendable {',
        '    /// The id of the thing.',
        '    public var id: String',
        '    /// Format: `date-time`.',
        '    public var createdAt: String',
        '    public var `default`: Int?',
        '    public var deletedAt: String?',
        '    public var note: String?',
        '    /// Always `"thing"` today.',
        '    public var kind: String',
        '    /// Always `true` today.',
        '    public var final: Bool',
        '    public var step: Step',
        '    public var colours: [Colour]?',
        '    public var scores: [String: Double]?',
        '    public var extra: TulaJSONValue?',
        '    public var nothing: AnswerNothing?',
        '    public var params: Params?'
      )
    )
  })

  test('the wire name is written wherever it differs from the property', () => {
    expect(schemas).toContain(
      lines(
        '    private enum CodingKeys: String, CodingKey {',
        '        case id',
        '        case createdAt = "created_at"',
        '        case `default`',
        '        case deletedAt'
      )
    )
  })

  test('the initializer: nil for what may be left out, the value of a const, nothing for a required key', () => {
    expect(schemas).toContain(
      lines(
        '    public init(',
        '        id: String,',
        '        createdAt: String,',
        '        `default`: Int? = nil,',
        '        deletedAt: String?,',
        '        note: String? = nil,',
        '        kind: String = "thing",',
        '        final: Bool = true,',
        '        step: Step,'
      )
    )
  })

  test('reading: a required key must be there, also where it may be null; an optional one may be missing', () => {
    expect(schemas).toContain('        self.id = try container.decode(String.self, forKey: .id)')
    expect(schemas).toContain(
      '        self.deletedAt = try container.decode(String?.self, forKey: .deletedAt)'
    )
    expect(schemas).toContain(
      '        self.note = try container.decodeIfPresent(String.self, forKey: .note)'
    )
    expect(schemas).toContain(
      '        self.`default` = try container.decodeIfPresent(Int.self, forKey: .`default`)'
    )
    // A const is read like any string: a value the server changes one day does not fail.
    expect(schemas).toContain(
      '        self.kind = try container.decode(String.self, forKey: .kind)'
    )
  })

  test('writing: a required key always (null when it has no value), an optional one only with a value', () => {
    expect(schemas).toContain('        try container.encode(self.deletedAt, forKey: .deletedAt)')
    expect(schemas).toContain('        try container.encodeIfPresent(self.note, forKey: .note)')
    expect(schemas).toContain('        try container.encode(self.kind, forKey: .kind)')
  })

  test('an object with no property is still an object when read and written', () => {
    expect(schemas).toContain(
      lines(
        'public struct AnswerNothing: Codable, Hashable, Sendable {',
        '    public init() {}',
        '',
        '    public init(from decoder: Decoder) throws {',
        '        _ = try decoder.container(keyedBy: TulaCodingKey.self)',
        '    }',
        '',
        '    public func encode(to encoder: Encoder) throws {',
        '        _ = encoder.container(keyedBy: TulaCodingKey.self)',
        '    }',
        '}'
      )
    )
  })

  test('an open enum keeps a member it does not know, and writes it back', () => {
    expect(schemas).toContain(
      lines(
        '/// A colour.',
        'public enum Colour: Codable, Hashable, Sendable {',
        '    case red',
        '    case darkBlue',
        // A member of the API called "unknown" does not take the name of the catch-all.
        '    case unknownValue',
        '    case _2tone',
        '    /// A value this version does not know, as the API wrote it.',
        '    case unknown(String)'
      )
    )
    expect(schemas).toContain(
      lines(
        '    public init(rawValue: String) {',
        '        switch rawValue {',
        '        case "red": self = .red',
        '        case "dark_blue": self = .darkBlue',
        '        case "unknown": self = .unknownValue',
        '        case "2tone": self = ._2tone',
        '        default: self = .unknown(rawValue)',
        '        }',
        '    }'
      )
    )
    expect(schemas).toContain(
      lines(
        '    public var rawValue: String {',
        '        switch self {',
        '        case .red: return "red"',
        '        case .darkBlue: return "dark_blue"',
        '        case .unknownValue: return "unknown"',
        '        case ._2tone: return "2tone"',
        '        case .unknown(let value): return value',
        '        }',
        '    }'
      )
    )
    expect(schemas).toContain(
      lines(
        '    public init(from decoder: Decoder) throws {',
        '        self.init(rawValue: try decoder.singleValueContainer().decode(String.self))',
        '    }'
      )
    )
    expect(schemas).toContain('        try container.encode(self.rawValue)')
    // Equal by what is on the wire, so `unknown("red")` is `red`.
    expect(schemas).toContain('        lhs.rawValue == rhs.rawValue')
  })

  test('a closed enum is a plain raw-value enum: no unknown case', () => {
    expect(schemas).toContain(
      lines(
        'public enum Size: String, Codable, Hashable, Sendable, CaseIterable {',
        '    case small',
        '    case extraLarge = "extra_large"',
        '}'
      )
    )
  })

  test('an open union decodes a tag it does not know to unknown, with the tag and the object', () => {
    expect(schemas).toContain(
      lines(
        '/// What to do next.',
        'public enum Step: Codable, Hashable, Sendable {',
        '    case needsPassword(StepNeedsPassword)',
        '    case complete(StepComplete)',
        '    /// A `status` this version does not know, with the object as the API wrote it.',
        '    case unknown(status: String, raw: TulaJSONValue)'
      )
    )
    expect(schemas).toContain(
      lines(
        '    public init(from decoder: Decoder) throws {',
        '        let container = try decoder.container(keyedBy: TulaCodingKey.self)',
        '        let tag = try container.decode(String.self, forKey: TulaCodingKey(stringValue: "status"))',
        '        switch tag {',
        '        case "needs_password": self = .needsPassword(try StepNeedsPassword(from: decoder))',
        '        case "complete": self = .complete(try StepComplete(from: decoder))',
        '        default: self = .unknown(status: tag, raw: try TulaJSONValue(from: decoder))',
        '        }',
        '    }'
      )
    )
    expect(schemas).toContain(
      lines(
        '    public func encode(to encoder: Encoder) throws {',
        '        switch self {',
        '        case .needsPassword(let value): try value.encode(to: encoder)',
        '        case .complete(let value): try value.encode(to: encoder)',
        '        case .unknown(_, let raw): try raw.encode(to: encoder)',
        '        }',
        '    }'
      )
    )
    expect(schemas).toContain(
      lines(
        '    public var status: String {',
        '        switch self {',
        '        case .needsPassword(let value): return value.status',
        '        case .complete(let value): return value.status',
        '        case .unknown(let value, _): return value',
        '        }',
        '    }'
      )
    )
  })

  test('a closed union has no unknown case and refuses a tag it does not know', () => {
    const how = schemas.slice(
      schemas.indexOf('public enum How'),
      schemas.indexOf('public struct HowByCode')
    )
    expect(how).toContain('    case byCode(HowByCode)')
    expect(how).not.toContain('unknown')
    expect(how).toContain(
      lines(
        '        default:',
        '            throw DecodingError.dataCorruptedError(',
        '                forKey: TulaCodingKey(stringValue: "method"),',
        '                in: container,',
        '                debugDescription: "How has no such method"',
        '            )'
      )
    )
  })

  test('a map that is a component is a name for the map', () => {
    expect(schemas).toContain('public typealias Params = [String: TulaJSONValue]')
  })

  test('a description cannot end its comment or start a line of code', () => {
    const text = renderSwiftSchemas(
      buildModel(
        fixture({
          Answer: {
            ...object({ a: { type: 'string', description: 'x\n}\npublic var hack: Int' } }),
            description: 'one\ntwo',
          },
        }),
        []
      )
    )
    expect(text).toContain('/// one two\n')
    expect(text).toContain('    /// x } public var hack: Int\n')
    expect(text).not.toMatch(/^public var hack/m)
  })
})

describe('the Swift operations file', () => {
  const text = renderSwiftOperations(model)

  test('is a table of data: id, method, path, whether a session is needed', () => {
    expect(text).toContain(
      lines(
        '    /// Do the thing (`POST /v1/client/things/{thingId}`). Body: `Request`. Answers `Answer`.',
        '    public static let doThing = TulaOperation(id: "doThing", method: "POST", path: "/v1/client/things/{thingId}", requiresSession: true)'
      )
    )
    expect(text).toContain(
      lines(
        '    /// askNothing (`DELETE /v1/client/nothing`). No body. Answers no body.',
        '    public static let askNothing = TulaOperation(id: "askNothing", method: "DELETE", path: "/v1/client/nothing", requiresSession: false)'
      )
    )
    expect(text).toContain(
      lines(
        '    public static let all: [TulaOperation] = [',
        '        askNothing,',
        '        doThing,',
        '    ]'
      )
    )
  })

  test('holds nothing that could make a request', () => {
    expect(text).not.toMatch(/URLSession|URLRequest|async|await|func /)
  })
})

