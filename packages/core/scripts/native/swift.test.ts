describe('the Swift theme file', () => {
  const text = renderSwiftTheme({ theme: DEFAULT_THEME, tokens: THEME_TOKENS })

  test('holds the default of every token, light and dark, as the string the contract holds', () => {
    for (const token of THEME_TOKENS) {
      if (token.scope === 'scheme') {
        const key = token.key as keyof typeof DEFAULT_THEME.light
        expect(text).toContain(
          `            ${token.key}: ${JSON.stringify(DEFAULT_THEME.light[key])}`
        )
        expect(text).toContain(
          `            ${token.key}: ${JSON.stringify(DEFAULT_THEME.dark[key])}`
        )
      } else {
        const value = DEFAULT_THEME[token.key as 'radius']
        expect(text).toContain(
          `        ${token.key}: ${JSON.stringify(value).replaceAll('\\"', '\\"')}`
        )
      }
      expect(text).toContain(
        `TulaThemeToken(key: "${token.key}", scope: "${token.scope}", type: "${token.type}"),`
      )
    }
    expect(text).toContain('    public static let defaults = TulaTheme(')
  })

  test('light and dark are both there and differ', () => {
    expect(text).toContain('            background: "#ffffff",')
    expect(text).toContain('            background: "#17171c",')
  })

  test('a value stays a string: no colour object, no parsing', () => {
    expect(text).not.toMatch(/Color|UIKit|SwiftUI|CGFloat/)
    expect(text.match(/^import .*$/gm)).toEqual(['import Foundation'])
  })

  test.each([
    ['a link', { light: { ...DEFAULT_THEME.light, primary: 'url(https://evil.example/x)' } }],
    ['more than a colour', { dark: { ...DEFAULT_THEME.dark, text: 'red; background: blue' } }],
    ['a variable', { radius: 'var(--x)' }],
    ['a value that is no string', { spacing: 4 as unknown as string }],
  ])('a default that the theme grammar refuses is never written: %s', (_name, change) => {
    expect(() =>
      renderSwiftTheme({ theme: { ...DEFAULT_THEME, ...change }, tokens: THEME_TOKENS })
    ).toThrow('has no value that passes its grammar')
  })

  test('the refusal does not repeat the value', () => {
    const theme = { ...DEFAULT_THEME, radius: 'expression(canary-9431)' }
    let message = ''
    try {
      renderSwiftTheme({ theme, tokens: THEME_TOKENS })
    } catch (error) {
      message = (error as Error).message
    }
    expect(message).toBe('theme token "radius" (shared) has no value that passes its grammar')
  })

  test('a token the theme has no value for fails; a key with no token is not written', () => {
    const { radius: _radius, ...withoutRadius } = DEFAULT_THEME
    expect(() =>
      renderSwiftTheme({ theme: withoutRadius as typeof DEFAULT_THEME, tokens: THEME_TOKENS })
    ).toThrow('theme token "radius" (shared)')
    const extra = { ...DEFAULT_THEME, canary: 'canary-7712' } as typeof DEFAULT_THEME
    expect(renderSwiftTheme({ theme: extra, tokens: THEME_TOKENS })).not.toContain('canary-7712')
  })
})

