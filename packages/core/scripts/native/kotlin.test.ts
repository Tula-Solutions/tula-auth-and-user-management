import { describe, expect, test } from 'bun:test'
import { DEFAULT_THEME, THEME_TOKENS } from '@tula-tech/contract/theme'
import { fixture, object, SAMPLE_SCHEMAS } from './fixture'
import {
  KOTLIN_PACKAGE,
  kotlinType,
  renderKotlinErrorCodes,
  renderKotlinOperations,
  renderKotlinSchemas,
  renderKotlinSupport,
  renderKotlinTheme,
} from './kotlin'
import { buildModel } from './model'

const model = buildModel(fixture(SAMPLE_SCHEMAS), [])
const schemas = renderKotlinSchemas(model)

/** The lines of `text`, joined: an expectation written as the lines the file must hold. */
const lines = (...text: string[]) => text.join('\n')

/** The `import` lines of a file, as written. */
const imports = (text: string): string[] => [...(text.match(/^import .*$/gm) ?? [])]

describe('kotlinType', () => {
  test.each([
    [{ kind: 'string' }, 'String'],
    [{ kind: 'integer' }, 'Long'],
    [{ kind: 'number' }, 'Double'],
    [{ kind: 'boolean' }, 'Boolean'],
    [{ kind: 'json' }, 'JsonElement'],
    [{ kind: 'named', name: 'FlowStep' }, 'FlowStep'],
    [{ kind: 'array', items: { kind: 'array', items: { kind: 'string' } } }, 'List<List<String>>'],
    [{ kind: 'map', values: { kind: 'named', name: 'Cell' } }, 'Map<String, Cell>'],
    [{ kind: 'array', items: { kind: 'nullable', of: { kind: 'integer' } } }, 'List<Long?>'],
  ] as const)('%j is %s', (type, expected) => {
    expect(kotlinType(type)).toBe(expected)
  })
})

describe('the Kotlin schemas file', () => {
  test('starts by saying it is generated and by which command, in its package', () => {
    expect(schemas.split('\n').slice(0, 8)).toEqual([
      '// Generated by `bun run native:generate` from packages/contract/openapi.json and @tula-tech/contract.',
      '// Do not edit: change the API or the contract, run `bun run contract:generate`, then regenerate this file.',
      '// A value of these types may hold tokens, passwords and attempt secrets: never log, print or interpolate one.',
      '',
      '@file:OptIn(ExperimentalSerializationApi::class)',
      '',
      `package ${KOTLIN_PACKAGE}`,
      '',
    ])
    expect(KOTLIN_PACKAGE).toBe('dev.tula.auth.generated')
    expect(schemas.endsWith(')\n')).toBe(true)
  })

  test('imports what it names, in order, from kotlinx.serialization and nowhere else', () => {
    const found = imports(schemas)
    expect(found).toEqual([...found].sort())
    expect(found.every((line) => line.startsWith('import kotlinx.serialization.'))).toBe(true)
    // The opt-in the file's first annotation names is imported too.
    expect(found).toContain('import kotlinx.serialization.ExperimentalSerializationApi')
    for (const line of found) {
      const name = line.slice(line.lastIndexOf('.') + 1)
      const uses = schemas.split('\n').filter((other) => other !== line && other.includes(name))
      expect(uses.length).toBeGreaterThan(0)
    }
  })

  test('a file that names nothing of the library imports nothing', () => {
    expect(imports(renderKotlinOperations(model))).toEqual([])
  })

  test('declarations are in order of name', () => {
    const names = [
      ...schemas.matchAll(/^(?:data class|class|sealed class|enum class|typealias) (\w+)/gm),
    ].map(([, name]) => name)
    expect(names).toEqual([...names].sort())
    expect(names).toEqual([
      'Answer',
      'AnswerNothing',
      'Colour',
      'How',
      'HowByCode',
      'HowByLink',
      'Params',
      'Request',
      'Size',
      'Step',
      'StepComplete',
      'StepNeedsPassword',
    ])
  })

  test('a property: the wire name where it differs, null where it may be left out, a const written always', () => {
    expect(schemas).toContain(
      lines(
        '/** What the thing answered. */',
        '@Serializable',
        'data class Answer(',
        '    /** The id of the thing. */',
        '    val id: String,',
        '    /** Format: `date-time`. */',
        '    @SerialName("created_at")',
        '    val createdAt: String,',
        // Optional: absent and null are both "no value".
        '    val default: Long? = null,',
        // Required and nullable: no default, so a missing key fails and null is written.
        '    val deletedAt: String?,',
        '    val note: String? = null,',
        '    /** Always `"thing"` today. */',
        '    @EncodeDefault',
        '    val kind: String = "thing",',
        '    /** Always `true` today. */',
        '    @EncodeDefault',
        '    val final: Boolean = true,',
        '    val step: Step,',
        '    val colours: List<Colour>? = null,',
        '    val scores: Map<String, Double>? = null,',
        '    val extra: JsonElement? = null,',
        '    val nothing: AnswerNothing? = null,',
        '    val params: Params? = null,',
        ')'
      )
    )
  })

  test('an object with no property is a class that equals every other of its kind', () => {
    expect(schemas).toContain(
      lines(
        '@Serializable',
        'class AnswerNothing {',
        '    override fun equals(other: Any?): Boolean = other is AnswerNothing',
        '',
        '    override fun hashCode(): Int = 0',
        '',
        '    override fun toString(): String = "AnswerNothing()"',
        '}'
      )
    )
  })

  test('an open enum keeps a member it does not know, and writes it back', () => {
    expect(schemas).toContain(
      lines(
        '/** A colour. */',
        '@Serializable(with = ColourSerializer::class)',
        'sealed class Colour {',
        '    /** The value as the API writes it. */',
        '    abstract val rawValue: String'
      )
    )
    expect(schemas).toContain(
      lines(
        '    object DarkBlue : Colour() {',
        '        override val rawValue: String = "dark_blue"',
        '    }'
      )
    )
    // A member of the API called "unknown" does not take the name of the catch-all, and a
    // member that starts with a digit is still a name.
    expect(schemas).toContain('    object UnknownValue : Colour() {')
    expect(schemas).toContain('    object _2tone : Colour() {')
    expect(schemas).toContain(
      lines(
        '    class Unknown internal constructor(override val rawValue: String) : Colour() {',
        '        override fun equals(other: Any?): Boolean = other is Unknown && other.rawValue == rawValue',
        '',
        '        override fun hashCode(): Int = rawValue.hashCode()',
        '    }'
      )
    )
    expect(schemas).toContain(
      lines(
        '        fun of(rawValue: String): Colour = when (rawValue) {',
        '            "red" -> Red',
        '            "dark_blue" -> DarkBlue',
        '            "unknown" -> UnknownValue',
        '            "2tone" -> _2tone',
        '            else -> Unknown(rawValue)',
        '        }'
      )
    )
    expect(schemas).toContain(
      lines(
        '    override fun deserialize(decoder: Decoder): Colour = Colour.of(decoder.decodeString())',
        '',
        '    override fun serialize(encoder: Encoder, value: Colour) {',
        '        encoder.encodeString(value.rawValue)',
        '    }'
      )
    )
  })

  test('the list of known members is made on first use', () => {
    // A member is an object nested in the class whose companion holds the list: built
    // eagerly, the list can be read while a member is still being made, and holds null.
    expect(schemas).toContain(
      lines(
        '        val known: List<Colour> by lazy {',
        '            listOf(',
        '                Red,',
        '                DarkBlue,',
        '                UnknownValue,',
        '                _2tone,',
        '            )',
        '        }'
      )
    )
    expect(schemas).not.toMatch(/val known: List<\w+> = listOf/)
  })

  test('a closed enum is a plain enum class: no unknown member', () => {
    expect(schemas).toContain(
      lines(
        '@Serializable',
        'enum class Size(val rawValue: String) {',
        '    @SerialName("small")',
        '    Small("small"),',
        '    @SerialName("extra_large")',
        '    ExtraLarge("extra_large"),',
        '}'
      )
    )
  })

  test('an open union decodes a tag it does not know to Unknown, with the tag and the object', () => {
    expect(schemas).toContain(
      lines(
        '/** What to do next. */',
        '@Serializable(with = StepSerializer::class)',
        'sealed class Step {',
        '    /** The value of `status` on the wire. */',
        '    abstract val status: String',
        '',
        '    data class NeedsPassword(val value: StepNeedsPassword) : Step() {',
        '        override val status: String get() = value.status',
        '    }',
        '',
        '    data class Complete(val value: StepComplete) : Step() {',
        '        override val status: String get() = value.status',
        '    }',
        '',
        '    /** A `status` this version does not know, with the object as the API wrote it. */',
        '    data class Unknown(override val status: String, val raw: JsonObject) : Step()',
        '}'
      )
    )
    expect(schemas).toContain(
      lines(
        '        return when (tag) {',
        '            "needs_password" -> Step.NeedsPassword(input.json.decodeFromJsonElement(StepNeedsPassword.serializer(), element))',
        '            "complete" -> Step.Complete(input.json.decodeFromJsonElement(StepComplete.serializer(), element))',
        '            else -> Step.Unknown(tag, element)',
        '        }'
      )
    )
    // Written back as the object that was read, not as what this version understood of it.
    expect(schemas).toContain('            is Step.Unknown -> value.raw')
  })

  test('a union is refused when it is no object, has no tag or is not JSON', () => {
    expect(schemas).toContain(
      lines(
        '        val input = decoder as? JsonDecoder',
        '            ?: throw SerializationException("Step is read from JSON only")',
        '        val element = input.decodeJsonElement() as? JsonObject',
        '            ?: throw SerializationException("Step is not an object")',
        // A tag that is a number or a boolean is no tag: only a JSON string is read.
        '        val tag = (element["status"] as? JsonPrimitive)?.takeIf { it.isString }?.content',
        '            ?: throw SerializationException("Step has no status")'
      )
    )
  })

  test('a closed union has no Unknown and refuses a tag it does not know, without repeating it', () => {
    const how = schemas.slice(
      schemas.indexOf('sealed class How'),
      schemas.indexOf('data class HowByCode')
    )
    expect(how).toContain('    data class ByCode(val value: HowByCode) : How() {')
    expect(how).not.toContain('Unknown')
    expect(how).toContain(
      '            else -> throw SerializationException("How has no such method")'
    )
    expect(how).not.toContain('$tag')
  })

  test('a map that is a component is a name for the map', () => {
    expect(schemas).toContain('typealias Params = Map<String, JsonElement>')
  })

  test('a description cannot end its comment', () => {
    const text = renderKotlinSchemas(
      buildModel(
        fixture({
          Answer: {
            ...object({ a: { type: 'string', description: 'x */ val hack = 1 /*' } }),
            description: 'one\ntwo',
          },
        }),
        []
      )
    )
    expect(text).toContain('/** one two */\n')
    expect(text).not.toContain('x */ val hack')
    expect(text.match(/\*\//g)?.length).toBe(text.match(/\/\*\*/g)?.length)
  })
})

describe('the Kotlin operations file', () => {
  const text = renderKotlinOperations(model)

  test('is a table of data: id, method, path, whether a session is needed', () => {
    expect(text).toContain(
      lines(
        '    /** Do the thing (`POST /v1/client/things/{thingId}`). Body: [Request]. Answers [Answer]. */',
        '    val doThing: TulaOperation = TulaOperation("doThing", "POST", "/v1/client/things/{thingId}", true)'
      )
    )
    expect(text).toContain(
      lines(
        '    /** askNothing (`DELETE /v1/client/nothing`). No body. Answers no body. */',
        '    val askNothing: TulaOperation = TulaOperation("askNothing", "DELETE", "/v1/client/nothing", false)'
      )
    )
    expect(text).toContain(
      lines(
        '    val all: List<TulaOperation> = listOf(',
        '        askNothing,',
        '        doThing,',
        '    )'
      )
    )
  })

  test('holds nothing that could make a request', () => {
    expect(text).not.toMatch(/suspend|HttpClient|okhttp|ktor|java\.net|fun /)
  })
})

describe('the Kotlin error codes file', () => {
  const text = renderKotlinErrorCodes({
    'auth.invalid_credentials': { status: 401, message: 'Say "no" for $5.' },
    rate_limited: { status: 429, message: 'Too many requests.' },
  })

  test('the open type has an object per code and an Unknown', () => {
    expect(text).toContain('sealed class ErrorCode {')
    expect(text).toContain(
      lines(
        '    object AuthInvalidCredentials : ErrorCode() {',
        '        override val rawValue: String = "auth.invalid_credentials"',
        '    }'
      )
    )
    expect(text).toContain('            "rate_limited" -> RateLimited')
    expect(text).toContain('            else -> Unknown(rawValue)')
  })

  test('every code has its status and its message; a dollar sign is no template', () => {
    expect(text).toContain(
      lines(
        '    /** `auth.invalid_credentials` */',
        '    val authInvalidCredentials: TulaErrorDefinition = TulaErrorDefinition(ErrorCode.AuthInvalidCredentials, 401, "Say \\"no\\" for \\$5.")'
      )
    )
    expect(text).toContain(
      lines(
        '    val all: List<TulaErrorDefinition> = listOf(',
        '        authInvalidCredentials,',
        '        rateLimited,',
        '    )'
      )
    )
  })
})

describe('the Kotlin theme file', () => {
  const text = renderKotlinTheme({ theme: DEFAULT_THEME, tokens: THEME_TOKENS })

  test('holds the default of every token, light and dark, as the string the contract holds', () => {
    for (const token of THEME_TOKENS) {
      if (token.scope === 'scheme') {
        const key = token.key as keyof typeof DEFAULT_THEME.light
        expect(text).toContain(
          `            ${token.key} = ${JSON.stringify(DEFAULT_THEME.light[key])},`
        )
        expect(text).toContain(
          `            ${token.key} = ${JSON.stringify(DEFAULT_THEME.dark[key])},`
        )
      } else {
        const value = DEFAULT_THEME[token.key as 'radius']
        expect(text).toContain(`        ${token.key} = ${JSON.stringify(value)},`)
      }
      expect(text).toContain(
        `        TulaThemeToken("${token.key}", "${token.scope}", "${token.type}"),`
      )
    }
  })

  test('light and dark are both there and differ', () => {
    expect(text).toContain('            background = "#ffffff",')
    expect(text).toContain('            background = "#17171c",')
  })

  test('a value stays a string: no colour object, no import', () => {
    expect(text).not.toMatch(/Color\(|androidx|android\.graphics|\.dp\b/)
    expect(imports(text)).toEqual([])
  })

  test.each([
    ['a link', { light: { ...DEFAULT_THEME.light, primary: 'url(https://evil.example/x)' } }],
    ['more than a colour', { dark: { ...DEFAULT_THEME.dark, text: 'red; background: blue' } }],
    ['a variable', { radius: 'var(--x)' }],
  ])('a default that the theme grammar refuses is never written: %s', (_name, change) => {
    expect(() =>
      renderKotlinTheme({ theme: { ...DEFAULT_THEME, ...change }, tokens: THEME_TOKENS })
    ).toThrow('has no value that passes its grammar')
  })
})

describe('the Kotlin support file', () => {
  test('declares the one JSON format: a key this version does not know is ignored', () => {
    const text = renderKotlinSupport()
    expect(text).toContain(
      lines('val TulaJson: Json = Json {', '    ignoreUnknownKeys = true', '}')
    )
    expect(imports(text)).toEqual(['import kotlinx.serialization.json.Json'])
    // Nothing else of the format is changed: a required key must be there, a default is not
    // written (but for a const, which is annotated), null is not coerced.
    expect(text).not.toMatch(/explicitNulls|coerceInputValues|isLenient|encodeDefaults/)
  })
})
