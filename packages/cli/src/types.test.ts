import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import type { AdminFetch } from '@tula-tech/admin'
import { COMMANDS, runCli } from './index'

// `tula types` (TULA-211): the environment's permission keys as a TypeScript union.

const SECRET_KEY = 'tula_sk_dev_typestest00000000000000000000000000'
let dir: string

beforeAll(() => {
  dir = mkdtempSync(join(tmpdir(), 'tula-types-'))
})
afterAll(() => {
  rmSync(dir, { recursive: true, force: true })
})

const role = (key: string, permissions: string[]) => ({
  id: key,
  key,
  name: key,
  permissions,
  builtIn: false,
  version: 1,
  createdAt: '2026-01-01T00:00:00.000Z',
  updatedAt: '2026-01-01T00:00:00.000Z',
})

/** Run `tula types` against a stubbed roles list; returns the generated file's text. */
async function generate(roles: ReturnType<typeof role>[], args: string[] = []) {
  const out = join(dir, `out-${Math.random().toString(36).slice(2)}.ts`)
  const fetch: AdminFetch = async () => Response.json({ data: roles })
  let stderr = ''
  const code = await runCli(
    ['types', '--out', out, ...args],
    {
      stdout: { write: () => {} },
      stderr: { write: (text) => (stderr += text) },
      env: { TULA_API_URL: 'http://localhost:3003', TULA_SECRET_KEY: SECRET_KEY },
      cwd: dir,
      isTTY: false,
      stdinIsTTY: false,
      fetch,
    },
    COMMANDS
  )
  return { code, stderr, out, text: code === 0 ? readFileSync(out, 'utf8') : '' }
}

describe('tula types', () => {
  test('no roles: both unions are never', async () => {
    const { code, text } = await generate([])
    expect(code).toBe(0)
    expect(text).toContain('Generated by `tula types`')
    expect(text).toContain('export type TulaPermission = never')
    expect(text).toContain('export type TulaRole = never')
    expect(text).toContain('export const TULA_PERMISSIONS = [] as const')
  })

  test('one role', async () => {
    const { text } = await generate([role('admin', ['org:billing:read'])])
    expect(text).toContain('export type TulaPermission = "org:billing:read"')
    expect(text).toContain('export type TulaRole = "admin"')
  })

  test('several roles: distinct keys, sorted, whatever the roles order', async () => {
    const { text } = await generate([
      role('member', ['org:b:read', 'org:a:read']),
      role('admin', ['org:b:read', 'org:c:read']),
    ])
    expect(text).toContain('"org:a:read" | "org:b:read" | "org:c:read"')
    expect(text).toContain('export type TulaRole = "admin" | "member"')
    expect(text).toContain(
      'export const TULA_PERMISSIONS = ["org:a:read", "org:b:read", "org:c:read"] as const'
    )
  })

  test('a key from the server is a safe string literal, never code', async () => {
    const evil = `x';process.exit(1);//"`
    const { text } = await generate([role('admin', [evil])])
    expect(text).toContain(JSON.stringify(evil))
  })

  // Three `bunx` starts at most; the type check is slow on a busy runner.
  test('a misspelled key fails to compile, a right one does not', async () => {
    const { text } = await generate([role('admin', ['org:billing:read'])])
    const check = (key: string) => {
      const tmp = mkdtempSync(join(dir, 'tsc-'))
      writeFileSync(join(tmp, 'tula-types.gen.ts'), text)
      writeFileSync(
        join(tmp, 'use.ts'),
        `import type { TulaPermission } from './tula-types.gen'\nexport const p: TulaPermission = '${key}'\n`
      )
      return Bun.spawnSync(
        ['bunx', 'tsc', '--noEmit', '--strict', '--target', 'es2022', join(tmp, 'use.ts')],
        { timeout: 60_000, cwd: tmp }
      )
    }
    expect(check('org:billing:read').exitCode).toBe(0)
    expect(check('org:biling:read').exitCode).not.toBe(0)
  }, 150_000)
})
