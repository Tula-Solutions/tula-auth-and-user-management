const NATIVE_NOTE =
  '<!-- Generated by `bun run docs:generate` from the doc comments in the native sources. Do not edit by hand. -->'

/** A public declaration as the page shows it. */
export interface NativeDeclaration {
  /** The name with the types it is declared in, e.g. `TulaClient.signOut`. */
  name: string
  /** `class`, `func`, `case`, … as the source writes it. */
  kind: string
  /** How many types it is declared inside. */
  nesting: number
  /** The declaration without its body. */
  code: string
  /** Its doc comment, as Markdown; empty when it has none. */
  documentation: string
}

/**
 * Blank out everything that is not code, a character for a character.
 *
 * Comments and the contents of string literals become spaces, so that a brace in a string
 * or a comment is never counted and a position in the result is the same position in the
 * source.
 *
 * @param text - A Swift or a Kotlin source.
 * @param language - Which of the two.
 * @returns The source with the same length and line breaks, holding code only.
 */
export function codeOnly(text: string, language: NativeLanguage): string {
  const out = text.split('')
  const blank = (from: number, to: number): void => {
    for (let k = from; k < to && k < out.length; k += 1) {
      if (out[k] !== '\n') {
        out[k] = ' '
      }
    }
  }
  const opensInterpolation = (at: number): boolean =>
    language === 'swift' ? text.startsWith('\\(', at) : text.startsWith('${', at)

  /** Skip code inside an interpolation until its closing bracket; returns the index after it. */
  function interpolation(start: number): number {
    const [open, close] = language === 'swift' ? ['(', ')'] : ['{', '}']
    let depth = 1
    let at = start
    while (at < text.length && depth > 0) {
      const char = text[at]
      if (char === '"') {
        at = string(at)
        continue
      }
      if (char === open) {
        depth += 1
      } else if (char === close) {
        depth -= 1
      }
      at += 1
    }
    return at
  }

  /** Skip the string literal that starts at `start`; returns the index after it. */
  function string(start: number): number {
    const triple = text.startsWith('"""', start)
    const quote = triple ? '"""' : '"'
    let at = start + quote.length
    while (at < text.length) {
      if (opensInterpolation(at)) {
        at = interpolation(at + 2)
        continue
      }
      if (text[at] === '\\' && !(triple && language === 'kotlin')) {
        at += 2
        continue
      }
      if (text.startsWith(quote, at)) {
        // A run of more than three quotes ends a triple-quoted string at its last three.
        while (triple && text[at + quote.length] === '"') {
          at += 1
        }
        return at + quote.length
      }
      if (!triple && text[at] === '\n') {
        return at
      }
      at += 1
    }
    return at
  }

  let at = 0
  while (at < text.length) {
    if (text.startsWith('//', at)) {
      const end = text.indexOf('\n', at)
      const stop = end === -1 ? text.length : end
      blank(at, stop)
      at = stop
    } else if (text.startsWith('/*', at)) {
      // Block comments nest, in Swift and in Kotlin alike.
      let open = 1
      let stop = at + 2
      while (stop < text.length && open > 0) {
        if (text.startsWith('/*', stop)) {
          open += 1
          stop += 2
        } else if (text.startsWith('*/', stop)) {
          open -= 1
          stop += 2
        } else {
          stop += 1
        }
      }
      blank(at, stop)
      at = stop
    } else if (language === 'swift' && text.startsWith('#"', at)) {
      // A raw string: no escape and no interpolation the scan has to follow.
      const end = text.indexOf('"#', at + 2)
      const stop = end === -1 ? text.length : end + 2
      blank(at + 2, stop - 2)
      at = stop
    } else if (text[at] === '"') {
      const stop = string(at)
      blank(at + 1, stop - 1)
      at = stop
    } else if (language === 'kotlin' && text[at] === "'") {
      const end = text[at + 1] === '\\' ? text.indexOf("'", at + 3) : text.indexOf("'", at + 2)
      const stop = end === -1 ? at + 1 : end + 1
      blank(at + 1, stop - 1)
      at = stop
    } else {
      at += 1
    }
  }
  return out.join('')
}

const SWIFT_MODIFIERS =
  /^(?:(?:public|open|internal|private|fileprivate|package|final|static|nonisolated|mutating|nonmutating|override|convenience|required|indirect|lazy|weak|unowned|dynamic)(?:\((?:set|unsafe)\))?\s+|class\s+(?=func|var|let|subscript)|@\w+(?:\([^)]*\))?\s+)*/
const SWIFT_DECLARATION =
  /^(struct|class|enum|protocol|extension|actor|func|var|let|typealias|case|subscript|associatedtype|init)\b\s*([`\w.]*)/

const KOTLIN_MODIFIERS =
  /^(?:(?:public|private|internal|protected|open|abstract|sealed|data|enum|value|annotation|inner|suspend|inline|operator|infix|override|const|lateinit|tailrec|external|companion|final|actual|expect)\s+|fun\s+(?=interface)|@\w+(?:\([^)]*\))?\s+)*/
const KOTLIN_DECLARATION =
  /^(class|interface|object|fun|val|var|typealias|constructor)\b\s*(?:<[^>]*>\s*)?((?:[\w<>?, ]+\.)?`?\w*`?)/

const TYPE_KINDS = new Set([
  'struct',
  'class',
  'enum',
  'protocol',
  'extension',
  'actor',
  'interface',
  'object',
])

interface Matched {
  kind: string
  name: string
  modifiers: string
}

function matchDeclaration(line: string, language: NativeLanguage): Matched | undefined {
  const modifiers = (
    line.match(language === 'swift' ? SWIFT_MODIFIERS : KOTLIN_MODIFIERS) as RegExpMatchArray
  )[0]
  const rest = line.slice(modifiers.length)
  const found = rest.match(language === 'swift' ? SWIFT_DECLARATION : KOTLIN_DECLARATION)
  if (!found) {
    return undefined
  }
  const kind = found[1] as string
  const written = (found[2] ?? '').trim()
  let name = written
  if (kind === 'init' || kind === 'constructor' || kind === 'subscript') {
    name = kind
  } else if (kind === 'object' && /\bcompanion\s/.test(modifiers) && written === '') {
    name = 'Companion'
  }
  if (name === '') {
    return undefined
  }
  return { kind, name, modifiers }
}

/** A type whose members are being read. */
interface Container {
  name: string
  /** The depth of braces its members are written at. */
  depth: number
  /** Whether what is declared in it can be public at all. */
  visible: boolean
  /** Whether a member is public without saying so. */
  implicit: boolean
  /** Whether a `case` in it is public without saying so (a public Swift enum). */
  cases: boolean
  /** Whether its entries are written as bare names (a Kotlin `enum class`). */
  entries: boolean
}

interface Signature {
  code: string
  /** Where the body's opening brace is, when there is one. */
  body: { line: number; column: number } | undefined
  /** The last line the declaration is written on. */
  end: number
}

const CONTINUES_BEFORE = /^(?::|where\b|->|\)|throws\b|async\b|rethrows\b)/
const CONTINUES_AFTER = /(?:,|:|->|&|\()$/

/**
 * Read a declaration from the line it starts on to where its body or its value begins.
 *
 * @param raw - The source's lines.
 * @param code - The same lines with comments and strings blanked ({@link codeOnly}).
 * @param start - The line the declaration starts on.
 * @returns The declaration without its body, and where the body opens.
 */
function readSignature(raw: string[], code: string[], start: number): Signature {
  const parts: string[] = []
  let round = 0
  let curly = 0
  for (let line = start; line < code.length; line += 1) {
    const text = code[line] as string
    const source = raw[line] as string
    for (let column = 0; column < text.length; column += 1) {
      const char = text[column]
      if (char === '(' || char === '[') {
        round += 1
      } else if (char === ')' || char === ']') {
        round -= 1
      } else if (char === '{') {
        if (round === 0 && curly === 0) {
          // A protocol's `{ get set }` is part of what is declared, not a body.
          const accessors = /^\{\s*(?:(?:get|set|async|throws|mutating|nonmutating)\s*)+\}\s*$/
          if (accessors.test(text.slice(column))) {
            parts.push(source)
            return { code: parts.join('\n'), body: undefined, end: line }
          }
          parts.push(source.slice(0, column))
          return { code: parts.join('\n'), body: { line, column }, end: line }
        }
        curly += 1
      } else if (char === '}') {
        curly -= 1
      } else if (char === '=' && round === 0 && curly === 0) {
        const before = text[column - 1] ?? ''
        const after = text[column + 1] ?? ''
        if (!'=!<>+-*/'.includes(before) && after !== '=' && after !== '>') {
          // A value written out on the one line (a default wording, a constant) is part of
          // what a reader wants; anything longer or unfinished is left out.
          const value = text.slice(column + 1).trim()
          const whole = source.trimEnd()
          if (value !== '' && whole.length <= 100 && /^[^(){}[\]]*$/.test(value)) {
            parts.push(whole)
            return { code: parts.join('\n'), body: undefined, end: line }
          }
          parts.push(source.slice(0, column))
          return { code: parts.join('\n'), body: undefined, end: line }
        }
      }
    }
    parts.push(source)
    if (round <= 0 && curly <= 0) {
      const next = (code[line + 1] ?? '').trim()
      if (!CONTINUES_AFTER.test(text.trim()) && !CONTINUES_BEFORE.test(next)) {
        return { code: parts.join('\n'), body: undefined, end: line }
      }
    }
  }
  return { code: parts.join('\n'), body: undefined, end: code.length - 1 }
}

function tidy(code: string): string {
  const lines = code.split('\n').map((line) => line.trimEnd())
  while (lines.length > 0 && (lines.at(-1) as string).trim() === '') {
    lines.pop()
  }
  const indent = Math.min(
    ...lines
      .filter((line) => line.trim() !== '')
      .map((line) => line.length - line.trimStart().length)
  )
  return lines.map((line) => line.slice(indent)).join('\n')
}

/** The names a member is declared under; a companion's members are its class's. */
function namesOf(stack: Container[]): string[] {
  return stack.map((container) => container.name).filter((name) => name !== 'Companion')
}

const KOTLIN_ENTRY = /^([A-Z][A-Z0-9_]*)\s*(?:\(.*\))?\s*[,;]?$/

/**
 * The public declarations of one native source, in the order they are written.
 *
 * @param text - The source.
 * @param language - Which language it is in.
 * @param path - The file's path, for the error.
 * @returns Every declaration an app can name, with its doc comment.
 * @throws Error when the braces of the file do not close: the scan lost its place.
 */
export function nativeDeclarations(
  text: string,
  language: NativeLanguage,
  path: string
): NativeDeclaration[] {
  const raw = text.split('\n')
  const code = codeOnly(text, language).split('\n')
  const found: NativeDeclaration[] = []
  const stack: Container[] = []
  let depth = 0
  let documentation: string[] = []
  let annotations: string[] = []
  let inBlock: 'doc' | 'plain' | undefined
  let pending: { line: number; column: number; container: Omit<Container, 'depth'> } | undefined
  let skipUntil = -1

  for (let line = 0; line < raw.length; line += 1) {
    const source = (raw[line] as string).trim()
    const text = (code[line] as string).trim()
    const top = stack.at(-1)

    if (text === '') {
      if (inBlock) {
        if (inBlock === 'doc') {
          const body = source.replace(/\*\/\s*$/, '').replace(/^\*+ ?/, '')
          if (!source.startsWith('*/')) {
            documentation.push(body)
          }
        }
        if (source.includes('*/')) {
          inBlock = undefined
        }
      } else if (source.startsWith('///')) {
        documentation.push(source.slice(3).replace(/^ /, ''))
      } else if (source.startsWith('/**') && !source.startsWith('/***')) {
        documentation = []
        const single = source.match(/^\/\*\*\s*(.*?)\s*\*\/$/)
        if (single) {
          documentation.push(single[1] as string)
        } else {
          const first = source.slice(3).trim()
          if (first !== '') {
            documentation.push(first)
          }
          inBlock = 'doc'
        }
      } else if (source.startsWith('/*')) {
        inBlock = source.includes('*/') ? undefined : 'plain'
      } else if (source === '') {
        documentation = []
        annotations = []
      }
      continue
    }

    const atMembers = top ? depth === top.depth : depth === 0
    if (line > skipUntil && atMembers && stack.every((container) => container.visible)) {
      if (/^@\w+(?:\(.*\))?$/.test(text)) {
        annotations.push(source)
      } else {
        const matched = matchDeclaration(text, language)
        const hidden =
          matched &&
          /\b(?:private|fileprivate|internal|protected|package)\b/.test(
            matched.modifiers.replace(/(?:private|fileprivate|internal)\(set\)/g, '')
          )
        const says = matched && /\b(?:public|open)\b/.test(matched.modifiers)
        const overrides = matched && /\boverride\b/.test(matched.modifiers)
        const companion = matched?.name === 'Companion'
        let shown = false
        if (matched && !hidden && !overrides) {
          if (language === 'kotlin') {
            // A companion is where its members are written, not something an app names.
            shown = !companion
          } else if (matched.kind === 'extension') {
            shown = false
          } else if (matched.kind === 'case') {
            shown = top?.cases === true
          } else {
            shown = says === true || top?.implicit === true
          }
        }
        if (matched) {
          const signature = readSignature(raw, code, line)
          if (shown) {
            const qualified = [...namesOf(stack), matched.name].join('.')
            found.push({
              name: qualified,
              kind: matched.kind,
              nesting: stack.length,
              // The annotations were read without their indentation: the declaration loses
              // its own before the two are joined.
              code: [
                ...annotations.filter((entry) => !entry.startsWith('@Suppress')),
                tidy(signature.code),
              ].join('\n'),
              documentation: documentation.join('\n').trim(),
            })
          }
          if (signature.body && TYPE_KINDS.has(matched.kind)) {
            const extension = matched.kind === 'extension'
            pending = {
              line: signature.body.line,
              column: signature.body.column,
              container: {
                name: matched.name,
                // An extension shows nothing by itself; what it declares can still be public.
                visible: extension || companion ? !hidden : shown,
                implicit:
                  language === 'swift' &&
                  ((matched.kind === 'protocol' && shown) || (extension && says === true)),
                cases: language === 'swift' && matched.kind === 'enum' && shown,
                entries: language === 'kotlin' && /\benum\s/.test(matched.modifiers),
              },
            }
          }
          skipUntil = signature.end
        } else if (language === 'kotlin' && top?.entries) {
          const entry = text.match(KOTLIN_ENTRY)
          if (entry) {
            found.push({
              name: [...namesOf(stack), entry[1] as string].join('.'),
              kind: 'entry',
              nesting: stack.length,
              code: entry[1] as string,
              documentation: documentation.join('\n').trim(),
            })
          }
        }
        documentation = []
        annotations = []
      }
    } else if (!/^@\w+(?:\(.*\))?$/.test(text)) {
      documentation = []
      annotations = []
    }

    const whole = code[line] as string
    for (let column = 0; column < whole.length; column += 1) {
      const char = whole[column]
      if (char === '{') {
        depth += 1
        if (pending && pending.line === line && pending.column === column) {
          stack.push({ ...pending.container, depth })
          pending = undefined
        }
      } else if (char === '}') {
        depth -= 1
        while (stack.length > 0 && depth < (stack.at(-1) as Container).depth) {
          stack.pop()
        }
      }
    }
  }
  if (depth !== 0 || stack.length !== 0) {
    throw new Error(`docs: lost the place in ${path} (its braces do not close for the scan)`)
  }
  return found
}

function sourcesOf(root: string, directory: string, language: NativeLanguage): string[] {
  const extension = language === 'swift' ? '.swift' : '.kt'
  const found: string[] = []
  function walk(path: string): void {
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      // The generated types have a reference of their own (ADR 0050).
      if (entry.isDirectory() && entry.name.toLowerCase() !== 'generated') {
        walk(join(path, entry.name))
      } else if (entry.isFile() && entry.name.endsWith(extension)) {
        found.push(join(path, entry.name))
      }
    }
  }
  walk(join(root, directory))
  // By code unit: `localeCompare` orders by the ICU data of whoever runs it.
  return found.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
}

/** What the generator wrote for the native SDKs. */
export interface NativeReference {
  /** Every page, by its path relative to the repository. */
  pages: Map<string, string>
  /** The index's rows, one a module. */
  index: string[]
}

/**
 * Write the reference pages of the native SDKs.
 *
 * @param root - The repository's root.
 * @returns The pages and the rows the index lists them with.
 * @throws Error when a source cannot be scanned.
 */
export function nativeReference(root: string): NativeReference {
  const pages = new Map<string, string>()
  const index: string[] = []
  for (const sdk of NATIVE_SDKS) {
    const lines: string[] = [
      NATIVE_NOTE,
      '',
      `# ${sdk.title}`,
      '',
      `Every declaration an app can name in the hand-written ${sdk.title} sources, with its doc`,
      `comment. The guide is [${sdk.guide.replace('../', 'docs/')}](${sdk.guide}).`,
      '',
      'The page is written from the text of the sources, not by a compiler: it shows what is',
      'declared and how it is documented, and does not show that it compiles. The generated',
      'types of the client API (the requests, the answers, the error codes) are not listed here.',
      '',
    ]
    for (const module of sdk.modules) {
      let count = 0
      let undocumented = 0
      lines.push(
        `## \`${module.name}\``,
        '',
        `\`${module.imported}\`, from \`${module.directory}\`.`,
        ''
      )
      for (const file of sourcesOf(root, module.directory, sdk.language)) {
        const path = relative(root, file).split('\\').join('/')
        const declarations = nativeDeclarations(readFileSync(file, 'utf8'), sdk.language, path)
        for (const declaration of declarations) {
          count += 1
          if (declaration.documentation === '') {
            undocumented += 1
          }
          lines.push(
            `${declaration.nesting === 0 ? '###' : '####'} \`${declaration.name}\``,
            '',
            `_${declaration.kind}_, defined in \`${path}\``,
            ''
          )
          if (declaration.documentation !== '') {
            lines.push(declaration.documentation, '')
          }
          lines.push(`\`\`\`${sdk.language}`, declaration.code, '```', '')
        }
      }
      index.push(
        `| [\`${module.name}\`](${sdk.page}) | ${sdk.title} | \`${module.directory}\` | ${count} | ${undocumented} |`
      )
    }
    pages.set(`docs/reference/${sdk.page}`, `${lines.join('\n').trimEnd()}\n`)
  }
  return { pages, index }
}
