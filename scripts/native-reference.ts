// The reference pages of the two native SDKs (docs/reference/swift.md, docs/reference/kotlin.md),
// written by `bun run docs:generate` from the doc comments of the hand-written sources.
//
// No job of `verify` has a Swift or a Kotlin toolchain, so this is a scan of the text and not
// a compiler's view: it reads declarations a line at a time, at the depth of braces where a
// type's members are. What it shows is that a declaration is written in the source with this
// signature and this comment, never that it compiles. A file it loses its place in (braces
// that do not close) stops the generation, by name: never a page with a silent gap.
//
// The generated types (ADR 0050) are not listed: they are data, written from the OpenAPI
// document, and the API's own reference describes them.

/** Which language a source is written in. */
export type NativeLanguage = 'swift' | 'kotlin'

/** One library of a native SDK: its name as an app imports it and where its sources are. */
export interface NativeModule {
  /** The module's name, as the page's heading. */
  name: string
  /** What an app writes to use it. */
  imported: string
  /** The directory of its sources, relative to the repository. */
  directory: string
}

/** A native SDK with a reference page. */
export interface NativeSdk {
  language: NativeLanguage
  /** The page's file name under `docs/reference/`. */
  page: string
  title: string
  /** The guide the page links back to, relative to `docs/reference/`. */
  guide: string
  modules: NativeModule[]
}

